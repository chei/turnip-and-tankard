export type CharacterClass = 'warrior' | 'mage' | 'rogue' | 'ranger' | 'villager';

export interface Look {
  cls: CharacterClass;
  skin: number;
  hair: number;
  hairStyle: string;
  beard: string;
  headgear: string;
  outfit: number;
}

const HEADGEAR_BY_CLASS: Record<CharacterClass, string[]> = {
  warrior: ['helmet', 'horned', 'none'],
  mage: ['wizard'],
  rogue: ['hood', 'bandana'],
  ranger: ['cap', 'cap', 'none'],
  villager: ['none', 'none', 'straw', 'bandana'],
};

function pick<T>(list: readonly T[], n: number): T {
  return list[Math.abs(n) % list.length]!;
}

/** A deterministic appearance from a class and a seed. */
export function lookFromSeed(cls: CharacterClass, seed: number): Look {
  const bits = (shift: number) => (seed >>> shift) & 0xff;
  const headgear = pick(HEADGEAR_BY_CLASS[cls], bits(0));
  const hairStyle = pick(['short', 'long', 'bun', 'spiky', 'short', 'long'], bits(3));
  const beard = hairStyle === 'long' || hairStyle === 'bun' ? 'none' : pick(['none', 'none', 'short', 'long'], bits(6));
  return {
    cls,
    skin: bits(9) % SKIN_TONES.length,
    hair: bits(12) % HAIR_COLOURS.length,
    hairStyle,
    beard: headgear === 'hood' ? 'none' : beard,
    headgear,
    outfit: bits(15) % OUTFITS[cls]!.length,
  };
}

function swapsFor(look: Look): Swaps {
  const [skin, skinShade] = SKIN_TONES[look.skin % SKIN_TONES.length]!;
  const [hair, hairShade] = HAIR_COLOURS[look.hair % HAIR_COLOURS.length]!;
  const outfits = OUTFITS[look.cls]!;
  const [outfit, outfitShade, trim] = outfits[look.outfit % outfits.length]!;
  return {
    s: skin,
    S: skinShade,
    h: hair,
    H: hairShade,
    f: outfit,
    F: outfitShade,
    j: trim,
    E: '#1f1420',
    M: skinShade,
    q: '#f29cb4',
  };
}

export function drawCharacter(ctx: CanvasRenderingContext2D, look: Look, x: number, y: number, blink = false): void {
  const swaps = swapsFor(look);
  if (blink) swaps.E = swaps.S!;
  drawSprite(ctx, BODY, x, y + 4, swaps);
  const hair = HAIR[look.hairStyle] ?? HAIR.short!;
  drawSprite(ctx, hair, x, y + HAIR_Y, swaps);
  const beard = BEARD[look.beard] ?? BEARD.none!;
  drawSprite(ctx, beard, x, y + BEARD_Y, swaps);
  const gear = HEADGEAR[look.headgear] ?? HEADGEAR.none!;
  drawSprite(ctx, gear.art, x, y + gear.y, swaps);
}

export function characterCanvas(look: Look, scale = 1): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = CHAR_W * scale;
  canvas.height = CHAR_H * scale;
  const ctx = canvas.getContext('2d')!;
  ctx.scale(scale, scale);
  drawCharacter(ctx, look, 0, 0);
  return canvas;
}

export function lookKey(look: Look): string {
  return [look.cls, look.skin, look.hair, look.hairStyle, look.beard, look.headgear, look.outfit].join('-');
}
